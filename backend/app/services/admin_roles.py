"""管理員名單核對（憲章原則 IV，spec FR-005～FR-009）。

★ 為什麼是「核對名單」而不是「一支指派 API」
=============================================
管理員身分由後端指定、不開放自行申請。三種可能做法中選了名單：

  1. 部署設定的名單 + 登入時核對   ← 採用
  2. 直接改資料庫的 role 欄位       ← 保留為緊急撤銷手段
  3. 只有特定金鑰能呼叫的指派 API   ← **否決**

否決 3 的理由：它會新增一條在另外兩案中根本不存在的提權路徑（一支能寫
role 的端點 + 一組要保管的金鑰）。攻擊面最大的方案不該是預設方案。

★ 雙向同步，不是只升不降
========================
名單是單一真實來源，故不在名單內者必須被降回一般使用者。只升不降會讓
「從名單移除」完全失效——而那正是撤銷管理員的主要手段（FR-007）。

⚠️ 由此推得一個維運上必須知道的結果：**直接在資料庫把 role 改成 admin
   是無效的**，下次登入就會被名單覆寫。授予一律走名單；資料庫直改只能
   用於緊急撤銷，且撤銷後必須同步把該帳號移出名單，否則下次登入即復原。

★ 安全性
========
line_user_id 來自 LINE 官方 verify endpoint 回傳的 `sub`（見 line_auth.py），
**不是客戶端可自行宣告的值**，故使用者無法藉偽造請求把自己放進名單。
核對發生在身分驗證完成之後，不影響驗證邏輯本身（憲章原則 I）。
"""

from app.core.config import get_settings
from app.db.models import ROLE_ADMIN, ROLE_USER


def resolve_role(line_user_id: str) -> str:
    """依部署設定的名單判定角色。

    純函式、不碰資料庫——這讓它的測試可在無 Docker 的環境執行，也讓
    「誰是管理員」這個判斷只有一處實作可查。

    比對為**完整字串相等**（frozenset 成員檢查），不做前綴或子字串比對，
    避免 `U123` 意外匹配到 `U1234...`。
    """
    if not line_user_id:
        return ROLE_USER

    return ROLE_ADMIN if line_user_id in get_settings().admin_line_user_id_set else ROLE_USER
